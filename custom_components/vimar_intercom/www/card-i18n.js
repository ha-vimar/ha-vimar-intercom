let lang = "en";

// "it", "it-IT", "pt_BR"... -> the table's language, or "en".
const langOf = (hass) => {
  const l = String(hass?.locale?.language || hass?.language || "").toLowerCase().split(/[-_]/)[0];
  return STRINGS[l] ? l : "en";
};

// Called with every hass the card or the editor gets. One page has one HA user, so the
// language is module-wide.
const setLang = (hass) => {
  lang = langOf(hass);
};

const t = (key, vars) => {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, n) => vars[n] ?? "") : s;
};

export { STRINGS, langOf, setLang, t };
